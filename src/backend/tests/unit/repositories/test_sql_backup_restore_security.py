"""A ``.sql`` backup restores only what the exporter writes, or nothing.

Apps security scan triage (2026-10-28): ``restore_postgres_backup`` executed
every statement of the downloaded file verbatim (anyone able to write the volume
ran arbitrary SQL at the next restore), swallowed each failure and reported
success, and split the file treating ``\\`` as an escape — so one value ending
in a backslash silently dropped every statement after it.
"""

import asyncio
from unittest.mock import AsyncMock, MagicMock

import pytest

from src.repositories.database_backup_repository import DatabaseBackupRepository
from src.utils.sql_backup_format import BackupFormatError, restore_statements

DUMP = """-- Kasal Database Backup
-- Generated by Kasal on 2026-10-28T12:00:00
--

SET statement_timeout = 0;
SET client_encoding = 'UTF8';
SET standard_conforming_strings = on;

-- Table: agents

ALTER TABLE agents DISABLE TRIGGER ALL;
DELETE FROM agents;

INSERT INTO agents (id, path, note) VALUES (1, 'C:\\data\\', 'semi; colon');
INSERT INTO agents (id, path, note) VALUES (2, 'line1
-- still data, not a comment
line3', '{"a": "it''s"}'::jsonb);

ALTER TABLE agents ENABLE TRIGGER ALL;

-- End of backup
-- Total rows: 2
"""


class TestBackupFormat:
    def test_every_exported_statement_is_kept(self):
        statements = restore_statements(DUMP)
        assert len(statements) == 8
        assert [s.insert_table for s in statements].count("agents") == 2

    def test_a_trailing_backslash_does_not_swallow_later_statements(self):
        last = restore_statements(DUMP)[-1]
        assert last.sql == "ALTER TABLE agents ENABLE TRIGGER ALL"

    def test_a_multiline_value_keeps_its_dash_dash_line(self):
        second_insert = restore_statements(DUMP)[6].sql
        assert "-- still data, not a comment" in second_insert

    @pytest.mark.parametrize(
        "stmt",
        [
            "DROP TABLE users;",
            "SET role = postgres;",
            "GRANT ALL ON agents TO public;",
            "INSERT INTO agents (id) VALUES ((SELECT secret FROM apikeys));",
            "INSERT INTO agents (id) VALUES (pg_read_file('/etc/passwd'));",
            "INSERT INTO agents (id, path) VALUES (1);",
            "INSERT INTO agents (id) VALUES ('never closed);",
            "DELETE FROM agents WHERE 1=1;",
        ],
    )
    def test_anything_the_exporter_never_writes_is_refused(self, stmt):
        with pytest.raises(BackupFormatError):
            restore_statements(DUMP + stmt)


def _repository(content: bytes):
    session = MagicMock()
    session.execute = AsyncMock()
    session.commit = AsyncMock()
    session.rollback = AsyncMock()
    repo = DatabaseBackupRepository(session)
    repo.volume_repo = MagicMock()
    repo.volume_repo.download_file_from_volume = AsyncMock(
        return_value={"success": True, "content": content}
    )
    return repo, session


def _restore(repo):
    return asyncio.run(
        repo.restore_postgres_backup("cat", "sch", "vol", "kasal_backup.sql")
    )


class TestRestore:
    def test_a_valid_backup_is_restored(self):
        repo, session = _repository(DUMP.encode())
        result = _restore(repo)
        assert result["success"] is True
        assert result["restored_tables"] == ["agents"] and result["total_rows"] == 2
        assert session.execute.await_count == 8
        session.commit.assert_awaited_once()

    def test_a_tampered_backup_runs_nothing(self):
        repo, session = _repository((DUMP + "DROP TABLE users;").encode())
        result = _restore(repo)
        assert result["success"] is False
        session.execute.assert_not_called()
        session.commit.assert_not_called()

    def test_a_failing_statement_rolls_back_and_says_so(self):
        repo, session = _repository(DUMP.encode())
        session.execute.side_effect = [None] * 5 + [RuntimeError("constraint")]
        result = _restore(repo)
        assert result["success"] is False
        assert "statement 6" in result["error"]
        session.rollback.assert_awaited_once()
        session.commit.assert_not_called()


class TestIdentifierValidator:
    def test_a_trailing_newline_is_not_an_identifier(self):
        """``re.match`` with ``$`` admitted ``"agents\\n"``; fullmatch does not."""
        with pytest.raises(ValueError):
            DatabaseBackupRepository._validate_identifier("agents\n")
        assert DatabaseBackupRepository._validate_identifier("agents") == "agents"


class TestSqliteRestoreColumnNames:
    """Column names of an uploaded ``.db`` were interpolated unchecked, and the
    target table was cleared before the INSERT that then failed."""

    HOSTILE = "x) VALUES (1); DROP TABLE agents; --"

    def _restore(self, tmp_path, backup_columns):
        import sqlite3

        backup = tmp_path / "backup.db"
        conn = sqlite3.connect(backup)
        conn.execute(f"CREATE TABLE agents ({backup_columns})")
        conn.execute("INSERT INTO agents VALUES (1, 'b')")
        conn.commit()
        conn.close()
        target = tmp_path / "target.db"
        conn = sqlite3.connect(target)
        conn.execute("CREATE TABLE agents (id INTEGER, name TEXT)")
        conn.execute("INSERT INTO agents VALUES (7, 'kept')")
        conn.commit()
        conn.close()

        repo = DatabaseBackupRepository(MagicMock())
        repo.volume_repo = MagicMock()
        repo.volume_repo.download_file_from_volume = AsyncMock(
            return_value={"success": True, "content": backup.read_bytes()}
        )
        asyncio.run(
            repo.restore_sqlite_backup(
                "cat", "sch", "vol", "backup.db", str(target), False
            )
        )
        conn = sqlite3.connect(target)
        rows = conn.execute("SELECT id, name FROM agents ORDER BY id").fetchall()
        conn.close()
        return rows

    def test_a_hostile_column_skips_the_table_and_leaves_it_intact(self, tmp_path):
        rows = self._restore(tmp_path, f'id INTEGER, "{self.HOSTILE}" TEXT')
        assert rows == [(7, "kept")]

    def test_plain_columns_still_restore(self, tmp_path):
        assert self._restore(tmp_path, "id INTEGER, name TEXT") == [(1, "b")]
